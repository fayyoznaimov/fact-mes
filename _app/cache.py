"""Короткая память для тяжёлых отчётов: один считает, остальные ждут.

Отчёт за 30 дней по 80 станкам считается сотни миллисекунд, а открывают его
мастер, начальник и экран в кабинете почти одновременно. Данные дописываются
раз в две минуты, так что готовый ответ можно держать минуту-две.

Главное здесь — не срок хранения, а очередь: без неё десять одновременных
запросов одного и того же отчёта считали бы его десять раз параллельно и мешали
друг другу. Нагрузочная проверка это и показала: «Узкие места» — 8 секунд у
каждого двадцатого запроса, сводка ручных остановов — 2 секунды в среднем.

Когда сборщик дописал новые смены и остановы, всё посчитанное сбрасывается
(`clear`): отчёт не отстаёт от данных дольше, чем нужно.
"""
import threading
import time

_data = {}              # ключ -> (когда посчитано, значение, поколение)
_locks = {}
_guard = threading.Lock()
_gen = [0]
MAX_KEYS = 400


def get(key, ttl, build):
    """Значение по ключу, если оно моложе ttl секунд; иначе посчитать —
    но только одному потоку, остальные дождутся его результата."""
    hit = _data.get(key)
    if hit and hit[2] == _gen[0] and time.time() - hit[0] < ttl:
        return hit[1]
    with _guard:
        lock = _locks.setdefault(key, threading.Lock())
    with lock:
        hit = _data.get(key)
        if hit and hit[2] == _gen[0] and time.time() - hit[0] < ttl:
            return hit[1]
        gen = _gen[0]
        value = build()
        if len(_data) >= MAX_KEYS:
            # Старшую половину выбрасываем: ключи — это периоды и дни отчётов,
            # их набор со временем только растёт.
            for k, _ in sorted(_data.items(), key=lambda kv: kv[1][0])[:MAX_KEYS // 2]:
                _data.pop(k, None)
        _data[key] = (time.time(), value, gen)
        return value


def clear():
    """Пришли новые данные — всё посчитанное раньше устарело."""
    _gen[0] += 1
